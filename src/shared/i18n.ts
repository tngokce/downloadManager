const dictionaries: Record<Language, Record<I18nKey, string>> = { tr, en }

export function translate(lang: Language, key: I18nKey, vars?: Record<string, string | number>): string {
  let s = dictionaries[lang]?.[key] ?? tr[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}

/** "expired:403" -> "Bağlantının süresi dolmuş… (403)" */
export function translateError(lang: Language, code: string | undefined): string {
  if (!code) return ''
  const idx = code.indexOf(':')
  const head = idx >= 0 ? code.slice(0, idx) : code
  const detail = idx >= 0 ? code.slice(idx + 1) : ''
  const key = `err.${head}` as I18nKey
  if (!(key in tr)) return code
  if (detail === 'rangeRejected') return translate(lang, 'err.rangeRejected')
  return detail ? `${translate(lang, key)} (${detail})` : translate(lang, key)
}

/** Yerleşik kategori/kuyruk adlarını çevirir; kullanıcının verdiği adlar olduğu gibi kalır. */
export function displayName(lang: Language, kind: 'cat' | 'queue', item: { id: string; name: string; builtin?: boolean }): string {
  if (!item.builtin) return item.name
  const key = `${kind}.${item.id}` as I18nKey
  return key in tr ? translate(lang, key) : item.name
}
